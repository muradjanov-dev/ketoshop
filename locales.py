def get_month_name(month: int, lang: str) -> str:
    names = MONTH_NAMES.get(lang, MONTH_NAMES["uz"])
    return names[month] if 1 <= month <= 12 else str(month)


def get_text(key: str, lang: str, **kwargs) -> str:
    """Get localized text with optional formatting.

    Languages:
      - "uz"     — Latin Uzbek (canonical source)
      - "uz_cyr" — Cyrillic Uzbek; falls back to auto-transliterating "uz"
                   when an explicit Cyrillic value isn't supplied
      - "ru"     — Russian
    """
    entries = TEXTS.get(key, {})
    if lang == "uz_cyr":
        text = entries.get("uz_cyr")
        if text is None:
            # Auto-derive from the Latin source. Lazy import keeps the module
            # graph clean (translit only runs when this branch is taken).
            from translit import lat_to_cyr
            uz_lat = entries.get("uz") or entries.get("ru") or f"[{key}]"
            text = lat_to_cyr(uz_lat)
    else:
        text = entries.get(lang, entries.get("uz", f"[{key}]"))
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def get_category_name(cat_key: str, lang: str) -> str:
    """Get localized category name"""
    return get_text(f"cat_{cat_key}", lang)


def register_category(key: str, name_uz: str, name_ru: str | None = None) -> None:
    """Make a DB-added category (see database.categories) resolvable by
    get_category_name/CATEGORIES exactly like the original hardcoded ones,
    without changing how any of the many call sites use those two names.
    Called once per category at startup (database.sync_categories) and again
    immediately whenever an admin creates a new one — no restart needed."""
    TEXTS[f"cat_{key}"] = {"uz": name_uz, "ru": name_ru or name_uz}
    if key not in CATEGORIES:
        CATEGORIES.append(key)


def reorder_categories(ordered_keys: list[str]) -> None:
    """Rebuilds CATEGORIES' order in place — same list object every other
    module already holds a reference to via `from locales import
    CATEGORIES`, so a slice-assignment (not a rebind) is required for the
    new order to actually show up everywhere."""
    known = set(CATEGORIES)
    CATEGORIES[:] = [k for k in ordered_keys if k in known] + [k for k in CATEGORIES if k not in ordered_keys]


