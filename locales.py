def localize_product_text(text_uz: str | None, text_ru: str | None, lang: str) -> str:
    """Pick the right rendering of a seller-supplied string (product name,
    description, etc.) for the given UI language.

    - "ru"     → prefer the Russian translation if present
    - "uz_cyr" → auto-transliterate the Latin Uzbek source to Cyrillic
    - "uz"     → transliterate Cyrillic seller input back to Latin so a
                 Latin reader doesn't end up with a Cyrillic description
                 just because the seller typed it that way

    Empty fields collapse to ''. Both transliteration directions are
    idempotent on already-correct input (Latin chars aren't in the Cyrillic
    map, and vice-versa).
    """
    if lang == "ru" and text_ru:
        return text_ru
    base = text_uz or ""
    if not base:
        return base
    if lang == "uz_cyr":
        from translit import lat_to_cyr
        return lat_to_cyr(base)
    if lang == "uz":
        from translit import cyr_to_lat
        return cyr_to_lat(base)
    return base
